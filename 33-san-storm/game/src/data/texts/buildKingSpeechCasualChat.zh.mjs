function buildStyle(styleKey, target, seed) {
  const rng = mulberry32(seed);
  const { first, second } = PAIRS[styleKey];
  const out = [];
  const seen = new Set();
  let guard = 0;
  while (out.length < target && guard < 200000) {
    guard += 1;
    const f = first[Math.floor(rng() * first.length)];
    const s = second[Math.floor(rng() * second.length)];
    const line = `${f}${s}`;
    const hn = countHan(line);
    if (hn < 10 || hn > 30) continue;
    if (seen.has(line)) continue;
    seen.add(line);
    out.push(line);
  }
  if (out.length < target) {
    throw new Error(`[buildKingSpeechCasualChat] ${styleKey} 仅 ${out.length}/${target}，请扩充 PAIRS.${styleKey} 词条`);
  }
  return out.slice(0, target);
}

