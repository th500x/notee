/**
 * 获取随机名字
 * @returns {string} 随机的文艺名字
 */
export function getRandomName() {
  const randomIndex = Math.floor(Math.random() * literaryNames.length);
  return literaryNames[randomIndex];
}

/**
 * 获取多个随机名字（不重复）
 * @param {number} count - 需要的名字数量
 * @returns {string[]} 随机名字数组
 */
export function getRandomNames(count = 3) {
  const shuffled = [...literaryNames].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, literaryNames.length));
}
